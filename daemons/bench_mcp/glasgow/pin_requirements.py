"""Regenerates requirements.txt: every package at the exact version listed in PINS, with the sha256 of every Linux
file (wheels and the sdist) PyPI publishes for that version, so `pip install --require-hashes` accepts any of them
and nothing else. Run by a person when they bump a pin (`python3 pin_requirements.py > requirements.txt`); the
bench server never runs it. It reads only https://pypi.org/pypi/<name>/<version>/json."""
import json
import sys
import urllib.request

# Versions measured on 2026-11-08 (see DEPENDENCIES.md). Glasgow itself is installed from a source archive (install_glasgow.py).
PINS = [
    ("amaranth", "0.5.10"), ("amaranth-yosys", "0.50.0.0.post130"), ("click", "8.5.1"), ("colorama", "0.4.6"),
    ("enum-tools", "0.13.0"), ("fx2", "0.16"), ("importlib_resources", "7.1.0"), ("Jinja2", "3.1.6"),
    ("jschon", "0.11.1"), ("libusb1", "3.4.0"), ("MarkupSafe", "3.0.4"), ("packaging", "26.3"),
    ("platformdirs", "4.14.5"), ("pyccobs", "0.1.1"), ("Pygments", "2.21.0"), ("pyvcd", "0.4.2"),
    ("rfc3986", "2.0.0"), ("tqdm", "4.70.1"), ("typing_extensions", "4.16.0"), ("wasmtime", "47.0.1"),
    ("yowasp-nextpnr-ice40", "0.11.1.0.post826"), ("yowasp-runtime", "1.96"), ("yowasp-yosys", "0.70.0.0.post1259"),
    ("pdm-backend", "2.5.0"),
]
SKIP = ("win", "macosx", "ppc64", "s390x", "armv7", "i686", "riscv", "musllinux", "freebsd")


def hashes(name, version):
    # [@ANCHOR: glasgow_pin_hashes]
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=60) as r:
        files = json.load(r)["urls"]
    keep = [f for f in files if not any(s in f["filename"].lower() for s in SKIP) and f["packagetype"] in ("bdist_wheel", "sdist")]
    if not keep:
        sys.exit(f"{name} {version}: no usable files")
    return sorted(f["digests"]["sha256"] for f in keep)


def main():
    # [@ANCHOR: glasgow_pin_main]
    print("# Generated by pin_requirements.py (2026-11-08). Do not edit by hand. Install with --require-hashes (install_glasgow.py).")
    for name, version in sorted(PINS, key=lambda p: p[0].lower()):
        h = hashes(name, version)
        print(f"{name}=={version} \\")
        print(" \\\n".join(f"    --hash=sha256:{x}" for x in h))


if __name__ == "__main__":
    main()
